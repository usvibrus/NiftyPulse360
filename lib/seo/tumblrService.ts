import tumblr from 'tumblr.js'
import { prisma } from '@/lib/db/prisma'

function getClient() {
  const { TUMBLR_CONSUMER_KEY, TUMBLR_CONSUMER_SECRET, TUMBLR_TOKEN, TUMBLR_TOKEN_SECRET } = process.env
  if (!TUMBLR_CONSUMER_KEY || !TUMBLR_TOKEN) return null
  return tumblr.createClient({
    consumer_key: TUMBLR_CONSUMER_KEY,
    consumer_secret: TUMBLR_CONSUMER_SECRET!,
    token: TUMBLR_TOKEN,
    token_secret: TUMBLR_TOKEN_SECRET!,
  })
}

export async function postToTumblr() {
  const client = getClient()
  if (!client) { console.log('[tumblr] No credentials configured'); return { posted: 0 } }

  const siteUrl = process.env.NEXT_PUBLIC_SITE_URL || ''
  let posted = 0

  const stocks = await prisma.stockEvent.findMany({
    where: { tumblrPosted: false, isPublished: true },
    take: 10,
    orderBy: { publishedAt: 'desc' },
  })

  for (const s of stocks) {
    const verb = s.eventType === 'RISE' ? 'surged' : 'dropped'
    const emoji = s.eventType === 'RISE' ? '📈' : '📉'
    const color = s.eventType === 'RISE' ? '#10B981' : '#EF4444'
    const bgColor = s.eventType === 'RISE' ? '#ECFDF5' : '#FEF2F2'
    const date = new Date(s.eventDate).toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric' })
    const coverImage = `${siteUrl}/api/og?title=${encodeURIComponent(`${s.companyName} shares ${verb} ${Math.abs(s.changePercent).toFixed(1)}%`)}&symbol=${encodeURIComponent(s.symbol)}&change=${encodeURIComponent(`${Math.abs(s.changePercent).toFixed(1)}%`)}&type=${s.eventType}`

    const body = `
<img src="${coverImage}" alt="${s.companyName} stock movement" style="width:100%;border-radius:12px;margin-bottom:20px"/>

<div style="background:${bgColor};border-left:4px solid ${color};padding:16px;border-radius:8px;margin-bottom:20px">
<h2 style="margin:0;color:${color}">${emoji} ${Math.abs(s.changePercent).toFixed(1)}% ${verb.toUpperCase()}</h2>
<p style="margin:8px 0 0;color:#374151">${s.companyName} (NSE: ${s.symbol}) • ${date}</p>
</div>

<table style="width:100%;border-collapse:collapse;margin-bottom:20px">
<tr style="background:#F8FAFC"><td style="padding:10px;border:1px solid #E2E8F0"><strong>Open</strong></td><td style="padding:10px;border:1px solid #E2E8F0">₹${s.openPrice.toFixed(2)}</td><td style="padding:10px;border:1px solid #E2E8F0"><strong>Close</strong></td><td style="padding:10px;border:1px solid #E2E8F0">₹${s.closePrice.toFixed(2)}</td></tr>
<tr><td style="padding:10px;border:1px solid #E2E8F0"><strong>High</strong></td><td style="padding:10px;border:1px solid #E2E8F0">₹${s.highPrice.toFixed(2)}</td><td style="padding:10px;border:1px solid #E2E8F0"><strong>Low</strong></td><td style="padding:10px;border:1px solid #E2E8F0">₹${s.lowPrice.toFixed(2)}</td></tr>
<tr style="background:#F8FAFC"><td style="padding:10px;border:1px solid #E2E8F0"><strong>Volume</strong></td><td style="padding:10px;border:1px solid #E2E8F0" colspan="3">${Number(s.volume).toLocaleString('en-IN')}</td></tr>
</table>

${s.aiAnalysis ? `<div style="background:#F8FAFC;padding:16px;border-radius:8px;margin-bottom:20px"><h3 style="margin:0 0 8px">🔍 Analysis</h3><p style="margin:0;color:#4B5563;line-height:1.6">${s.aiAnalysis.slice(0, 600)}</p></div>` : ''}

<div style="text-align:center;margin-top:24px">
<a href="${siteUrl}/stocks/${s.slug}" style="display:inline-block;background:#1565C0;color:white;padding:12px 32px;border-radius:8px;text-decoration:none;font-weight:bold">📖 Read Full Analysis →</a>
</div>

<p style="color:#9CA3AF;font-size:12px;margin-top:20px;text-align:center"><em>Auto-generated by NiftyPulse360 • Not financial advice</em></p>`

    try {
      await new Promise<void>((resolve, reject) => {
        // eslint-disable-next-line @typescript-eslint/no-explicit-any
        (client as any).createPost('niftypulse360', {
          type: 'text',
          title: `${emoji} ${s.companyName} (${s.symbol}) ${verb} ${Math.abs(s.changePercent).toFixed(1)}% — ${date}`,
          body,
          tags: `stockmarket,NSE,${s.symbol},IndianStocks,${s.sector || 'Finance'},NiftyPulse360,investing`,
        }, (err: Error | null) => err ? reject(err) : resolve())
      })
      await prisma.stockEvent.update({ where: { id: s.id }, data: { tumblrPosted: true } })
      posted++
    } catch (error) {
      console.error(`[tumblr] Failed to post ${s.symbol}:`, error)
    }
  }

  return { posted }
}
